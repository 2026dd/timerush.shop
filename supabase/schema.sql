-- Time Rush order database. Run this entire file in Supabase SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.tr_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_phone text not null,
  customer_city text not null,
  customer_address text not null,
  customer_notes text not null default '',
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'pending' check (status in ('pending','confirmed','shipped','delivered','cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.tr_order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.tr_orders(id) on delete cascade,
  product_id text not null,
  product_name text not null,
  image text not null default '',
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  line_total numeric(12,2) generated always as (quantity * unit_price) stored
);

alter table public.tr_orders enable row level security;
alter table public.tr_order_items enable row level security;

-- Public customers can submit through the validated RPC only. No public reads.
drop policy if exists "Admins can read orders" on public.tr_orders;
create policy "Admins can read orders" on public.tr_orders for select to authenticated using (true);
drop policy if exists "Admins can update orders" on public.tr_orders;
create policy "Admins can update orders" on public.tr_orders for update to authenticated using (true) with check (true);
drop policy if exists "Admins can read order items" on public.tr_order_items;
create policy "Admins can read order items" on public.tr_order_items for select to authenticated using (true);

create or replace function public.tr_place_order(
  p_customer_name text, p_customer_phone text, p_customer_city text,
  p_customer_address text, p_customer_notes text default '', p_items jsonb default '[]'::jsonb
) returns table(order_id uuid, order_number bigint, total numeric)
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_order_id uuid;
  v_total numeric(12,2);
begin
  if length(trim(coalesce(p_customer_name,''))) < 2 then raise exception 'Please enter your full name'; end if;
  if length(trim(coalesce(p_customer_phone,''))) < 6 then raise exception 'Please enter a valid phone number'; end if;
  if length(trim(coalesce(p_customer_city,''))) < 2 then raise exception 'Please enter your city'; end if;
  if length(trim(coalesce(p_customer_address,''))) < 3 then raise exception 'Please enter your address'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 30 then
    raise exception 'Invalid order items';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_items) x
    where coalesce(x->>'product_id','') = ''
      or length(coalesce(x->>'product_name','')) not between 1 and 160
      or coalesce(x->>'quantity','') !~ '^[1-9][0-9]{0,2}$'
      or coalesce(x->>'unit_price','') !~ '^[0-9]+(\.[0-9]{1,2})?$'
  ) then raise exception 'Invalid order item details'; end if;
  select sum((x->>'quantity')::integer * (x->>'unit_price')::numeric) into v_total
  from jsonb_array_elements(p_items) x
  where (x->>'quantity') ~ '^[1-9][0-9]{0,2}$'
    and (x->>'unit_price') ~ '^[0-9]+(\.[0-9]{1,2})?$';
  if v_total is null or v_total <= 0 then raise exception 'Invalid order total'; end if;

  insert into public.tr_orders(customer_name,customer_phone,customer_city,customer_address,customer_notes,total)
  values(trim(p_customer_name),trim(p_customer_phone),trim(p_customer_city),trim(p_customer_address),coalesce(p_customer_notes,''),v_total)
  returning id into v_order_id;

  insert into public.tr_order_items(order_id,product_id,product_name,image,quantity,unit_price)
  select v_order_id, x->>'product_id', x->>'product_name', coalesce(x->>'image',''),
    (x->>'quantity')::integer, (x->>'unit_price')::numeric
  from jsonb_array_elements(p_items) x
  where (x->>'quantity') ~ '^[1-9][0-9]{0,2}$'
    and (x->>'unit_price') ~ '^[0-9]+(\.[0-9]{1,2})?$'
    and length(coalesce(x->>'product_name','')) between 1 and 160;

  return query select o.id, o.order_number, o.total from public.tr_orders o where o.id=v_order_id;
end; $$;
revoke all on function public.tr_place_order(text,text,text,text,text,jsonb) from public;
grant execute on function public.tr_place_order(text,text,text,text,text,jsonb) to anon, authenticated;
grant select, update on public.tr_orders to authenticated;
grant select on public.tr_order_items to authenticated;
